#!/usr/bin/env python3
"""Independent exact checker for the certificates of this release.

Python standard library only.  It shares no code with verifier/ (which is the frozen verifier that produced the
board reports); everything below was written separately so that the two implementations check each other.

strategy (lower bound)
    Each projector is P = V G^{-1} V^dag with G = V^dag V, V = the given spanning vectors, so P is an exact
    orthogonal projector by construction.  With Psi[a][b] = psi[a*dB + b],
        <psi| P (x) Q |psi> = sum_{b,b'} K[b][b'] Q[b][b'],   K = Psi^dag P Psi = U^dag G^{-1} U,  U = V^dag Psi,
    is evaluated in exact rational (or Gaussian-rational) arithmetic.  The violation is
        <psi|W|psi> / <psi|psi> - b0   (an exact rational).

sos (upper bound)
    1. Identity.  sum_ij Y_ij w_i^dag w_j = lambda*1 - W in the algebra generated by projectors A_x, B_y with
       A_x^2 = A_x, B_y^2 = B_y and [A_x, B_y] = 0.  Reduced words (no two equal adjacent letters on each side)
       form a basis, so the identity is checked coefficient by coefficient in integers (Y = Ynum / D).
    2. PSD at the stated shift, in exact integer arithmetic.  L is computed in binary64 floating point by
       exactly the loop of verifier/rescheck.c (same operation order; CPython does every float operation
       separately, so there is no fused multiply-add), from the same enclosing intervals of the entries of Y.
       L is then rounded to the grid 2^-K (K = 120).  No property of floating point is used after this point:
       for ANY real lower-triangular matrix L~,
           F = Y + sigma*I - L~ L~^T   (computed exactly, as integers over a common denominator)
           f = ceil(sqrt(sum F_ij^2))  (integer square root, rounded up)  >=  ||F||_F  >=  ||F||_2
       gives Y + (sigma + f) I = L~ L~^T + (F + f I) >= 0.  The certificate passes if tau_exact = sigma + f is at
       most the stated shift tau_stated; then Y + tau_stated I >= 0 holds exactly.
    3. For N <= 120 also an exact Bareiss (fraction-free) test that Y + tau_stated I is positive definite.
    The certified bound is lambda + N * tau - b0 (Theorem 1 of the paper).

usage:  exactcheck.py CERT.json[.gz] --catalog data/catalog.json [--sigma HEX --tau-stated P/Q] [--json]
"""
import argparse
import gzip
import json
import math
import re
import sys
from fractions import Fraction as Q
from operator import mul

K_BITS = 120          # grid of the rounded factor L~
BAREISS_MAX_N = 120   # exact Bareiss test of Y + tau_stated I up to this size


class Bad(Exception):
    pass


# ------------------------------------------------------------------ numbers

_RAT = re.compile(r"^[+-]?\d+(/\d+)?$")
_DEC = re.compile(r"^[+-]?(\d+(\.\d*)?|\.\d+)([eE][+-]?\d{1,3})?$")


def rational(x):
    if isinstance(x, bool) or isinstance(x, float):
        raise Bad(f"inexact number {x!r}")
    if isinstance(x, int):
        return Q(x)
    if isinstance(x, str) and (_RAT.match(x.strip()) or _DEC.match(x.strip())):
        return Q(x.strip())
    raise Bad(f"not an exact number: {x!r}")


class C:
    """Gaussian rational re + i im."""
    __slots__ = ("re", "im")

    def __init__(self, re_, im_=Q(0)):
        self.re, self.im = re_, im_

    def __add__(self, o):
        if not isinstance(o, C):
            o = C(o)
        return C(self.re + o.re, self.im + o.im)

    __radd__ = __add__

    def __sub__(self, o):
        if not isinstance(o, C):
            o = C(o)
        return C(self.re - o.re, self.im - o.im)

    def __rsub__(self, o):
        return C(o) - self

    def __mul__(self, o):
        if not isinstance(o, C):
            return C(self.re * o, self.im * o)
        return C(self.re * o.re - self.im * o.im, self.re * o.im + self.im * o.re)

    __rmul__ = __mul__

    def __truediv__(self, o):
        if not isinstance(o, C):
            return C(self.re / o, self.im / o)
        n = o.re * o.re + o.im * o.im
        return self * C(o.re / n, -o.im / n)

    def __neg__(self):
        return C(-self.re, -self.im)

    def __bool__(self):
        return bool(self.re) or bool(self.im)

    def conj(self):
        return C(self.re, -self.im)


def conj(z):
    return z.conj() if isinstance(z, C) else z


def entry(x, complex_field):
    if isinstance(x, list):
        if not complex_field or len(x) != 2:
            raise Bad("complex entry [re, im] outside a complex strategy")
        return C(rational(x[0]), rational(x[1]))
    q = rational(x)
    return C(q) if complex_field else q


def clear_denominators(vec):
    """Multiply a vector by a positive integer so that all entries become (Gaussian) integers."""
    l = 1
    for z in vec:
        for part in ((z.re, z.im) if isinstance(z, C) else (z,)):
            l = l * part.denominator // math.gcd(l, part.denominator)
    return [z * l for z in vec]


def solve(G, R):
    """X with G X = R (G square, invertible), by exact Gauss-Jordan elimination with nonzero pivots."""
    n = len(G)
    A = [list(G[i]) + list(R[i]) for i in range(n)]
    for c in range(n):
        p = next((r for r in range(c, n) if A[r][c]), None)
        if p is None:
            raise Bad("spanning vectors are linearly dependent")
        A[c], A[p] = A[p], A[c]
        piv = A[c][c]
        A[c] = [z / piv for z in A[c]]
        for r in range(n):
            if r != c and A[r][c]:
                f = A[r][c]
                A[r] = [a - f * b for a, b in zip(A[r], A[c])]
    return [row[n:] for row in A]


# ------------------------------------------------------------------ strategies

def strategy_violation(cand, ineq):
    """Exact violation <psi|W|psi>/<psi|psi> - b0 of a strategy certificate."""
    field = cand.get("field", "real")
    if field not in ("real", "complex"):
        raise Bad("field must be real or complex")
    cx = field == "complex"
    dA, dB = cand["dA"], cand["dB"]
    if not (isinstance(dA, int) and isinstance(dB, int) and dA >= 1 and dB >= 1):
        raise Bad("bad dimensions")
    mA, mB = ineq["mA"], ineq["mB"]
    if len(cand["A"]) != mA or len(cand["B"]) != mB or len(cand["psi"]) != dA * dB:
        raise Bad("wrong number of projectors or wrong state length")
    psi = clear_denominators([entry(e, cx) for e in cand["psi"]])     # scaling psi does not change the value
    Psi = [[psi[a * dB + b] for b in range(dB)] for a in range(dA)]
    zero = C(Q(0)) if cx else Q(0)

    def vectors(spec, d):
        if not isinstance(spec, list) or len(spec) > d:
            raise Bad("a projector is a list of at most d spanning vectors")
        vs = []
        for v in spec:
            if not isinstance(v, list) or len(v) != d:
                raise Bad("spanning vector of the wrong length")
            vs.append(clear_denominators([entry(e, cx) for e in v]))  # rescaling keeps the span
        return vs

    def gram(vs):
        return [[sum((conj(u[a]) * w[a] for a in range(len(u))), zero) for w in vs] for u in vs]

    # Alice: K_x = Psi^dag P_x Psi = U^dag G^{-1} U  (dB x dB), U = V^dag Psi
    Ks = []
    for spec in cand["A"]:
        vs = vectors(spec, dA)
        if not vs:
            Ks.append([[zero] * dB for _ in range(dB)])
            continue
        U = [[sum((conj(v[a]) * Psi[a][b] for a in range(dA)), zero) for b in range(dB)] for v in vs]
        X = solve(gram(vs), U)
        Ks.append([[sum((conj(U[i][b]) * X[i][c] for i in range(len(vs))), zero) for c in range(dB)]
                   for b in range(dB)])
    KI = [[sum((conj(Psi[a][b]) * Psi[a][c] for a in range(dA)), zero) for c in range(dB)] for b in range(dB)]
    # Bob: Q_y = W H^{-1} W^dag as an explicit dB x dB matrix
    Qs = []
    for spec in cand["B"]:
        ws = vectors(spec, dB)
        if not ws:
            Qs.append([[zero] * dB for _ in range(dB)])
            continue
        Wd = [[conj(w[b]) for b in range(dB)] for w in ws]                 # W^dag  (s x dB)
        Z = solve(gram(ws), Wd)                                             # H^{-1} W^dag
        Qs.append([[sum((ws[j][b] * Z[j][c] for j in range(len(ws))), zero) for c in range(dB)]
                   for b in range(dB)])

    def pair(Km, Qm):  # <psi| P (x) Q |psi> (unnormalised) = sum K[b][c] Q[b][c]
        return sum((Km[b][c] * Qm[b][c] for b in range(dB) for c in range(dB) if Qm[b][c]), zero)

    norm = sum((KI[b][b] for b in range(dB)), zero)
    val = zero
    for x in range(mA):
        if ineq["bA"][x]:
            val = val + rational(ineq["bA"][x]) * sum((Ks[x][b][b] for b in range(dB)), zero)
        for y in range(mB):
            if ineq["bAB"][x][y]:
                val = val + rational(ineq["bAB"][x][y]) * pair(Ks[x], Qs[y])
    for y in range(mB):
        if ineq["bB"][y]:
            val = val + rational(ineq["bB"][y]) * pair(KI, Qs[y])
    if cx:
        if val.im != 0 or norm.im != 0:
            raise Bad("Bell value is not real")
        val, norm = val.re, norm.re
    if norm <= 0:
        raise Bad("zero state")
    return val / norm - rational(ineq.get("b0", 0))


# ------------------------------------------------------------------ SOS identity

_TOK = re.compile(r"([AB])(\d+)")


def reduced(seq):
    out = []
    for s in seq:
        if not out or out[-1] != s:
            out.append(s)
    return tuple(out)


def word(s, mA, mB):
    if not isinstance(s, str):
        raise Bad(f"bad word {s!r}")
    t = s.replace(" ", "").replace("*", "")
    if _TOK.sub("", t):
        raise Bad(f"bad word {s!r}")
    a, b = [], []
    for p, k in _TOK.findall(t):
        k = int(k)
        if not 1 <= k <= (mA if p == "A" else mB):
            raise Bad(f"setting out of range in {s!r}")
        (a if p == "A" else b).append(k)
    return reduced(a), reduced(b)


def load_Y(spec, n):
    D = rational(spec["denominator"])
    if D.denominator != 1 or D <= 0:
        raise Bad("denominator must be a positive integer")
    Y = [[0] * n for _ in range(n)]
    if "upper" in spec:
        rows = spec["upper"]
        if len(rows) != n:
            raise Bad("Y.upper must have N rows")
        for i, row in enumerate(rows):
            if len(row) != n - i:
                raise Bad("Y.upper row of the wrong length")
            for t, e in enumerate(row):
                v = rational(e)
                if v.denominator != 1:
                    raise Bad("Y numerators must be integers")
                Y[i][i + t] = Y[i + t][i] = int(v)
    elif "entries" in spec:
        seen = set()
        for i, j, e in spec["entries"]:
            i, j = sorted((int(i), int(j)))
            if not 0 <= i <= j < n or (i, j) in seen:
                raise Bad("bad or repeated sparse entry")
            seen.add((i, j))
            v = rational(e)
            if v.denominator != 1:
                raise Bad("Y numerators must be integers")
            Y[i][j] = Y[j][i] = int(v)
    else:
        raise Bad("Y needs 'upper' or 'entries'")
    return int(D), Y


def sos_lambda(cand, ineq):
    """Check the identity exactly; return (lambda, N, D, Ynum)."""
    mA, mB = ineq["mA"], ineq["mB"]
    ws = [word(w, mA, mB) for w in cand["words"]]
    n = len(ws)
    if len(set(ws)) != n:
        raise Bad("repeated word after reduction")
    D, Y = load_Y(cand["Y"], n)
    coef = {}
    for i in range(n):
        ai, bi = ws[i][0][::-1], ws[i][1][::-1]
        for j in range(n):
            v = Y[i][j]
            if v:
                key = (reduced(ai + ws[j][0]), reduced(bi + ws[j][1]))
                coef[key] = coef.get(key, 0) + v
    want = {}
    for x in range(mA):
        if ineq["bA"][x]:
            want[((x + 1,), ())] = -D * rational(ineq["bA"][x])
        for y in range(mB):
            if ineq["bAB"][x][y]:
                want[((x + 1,), (y + 1,))] = -D * rational(ineq["bAB"][x][y])
    for y in range(mB):
        if ineq["bB"][y]:
            want[((), (y + 1,))] = -D * rational(ineq["bB"][y])
    for key in set(coef) | set(want):
        if key != ((), ()) and coef.get(key, 0) != want.get(key, 0):
            raise Bad(f"identity fails at word {key}: {coef.get(key, 0)} != {want.get(key, 0)} (times D)")
    lam = Q(coef.get(((), ()), 0), D)
    if "lambda" in cand and rational(cand["lambda"]) != lam:
        raise Bad("stated lambda differs from the identity coefficient")
    return lam, n, D, Y


# ------------------------------------------------------------------ PSD at the stated shift

def enclosure(q):
    """Smallest binary64 interval [lo, hi] containing the rational q."""
    f = float(q)                                     # CPython: correctly rounded int/int division
    if not math.isfinite(f):
        raise Bad("entry outside the binary64 range")
    e = Q(f)
    if e == q:
        return f, f
    return (math.nextafter(f, -math.inf), f) if e > q else (f, math.nextafter(f, math.inf))


def float_factor(Y, D, sigma):
    """binary64 Cholesky factor of mid(Y) + sigma I with the loop order of verifier/rescheck.c, or None."""
    n = len(Y)
    mid = []
    for i in range(n):
        row = []
        for j in range(i + 1):
            lo, hi = enclosure(Q(Y[i][j], D))
            row.append(0.5 * (lo + hi))
        mid.append(row)
    L = [[0.0] * (i + 1) for i in range(n)]
    for i in range(n):
        Li = L[i]
        for j in range(i + 1):
            Lj = L[j]
            s = mid[i][j] + (sigma if i == j else 0.0)
            for k in range(j):
                s -= Li[k] * Lj[k]
            if i == j:
                if not s > 0:
                    return None
                Li[i] = math.sqrt(s)
            else:
                Li[j] = s / Lj[j]
            if not math.isfinite(Li[j]):
                return None
    return L


def exact_shift(Y, D, sigma):
    """tau_exact = sigma + f (Fraction) with an exact proof that Y + tau_exact I >= 0, or None."""
    L = float_factor(Y, D, sigma)
    if L is None:
        return None
    s = 1 << K_BITS
    Li = [[round(Q(v) * s) for v in row] for row in L]   # exact rounding of each double to the 2^-K grid
    sq = Q(sigma)
    M = math.lcm(D, 1 << (2 * K_BITS), sq.denominator)
    cY, cS, cL = M // D, sq.numerator * (M // sq.denominator), M >> (2 * K_BITS)
    ss = 0
    for i in range(len(Y)):
        ri, Yi = Li[i], Y[i]
        for j in range(i + 1):
            F = Yi[j] * cY - sum(map(mul, ri[:j + 1], Li[j][:j + 1])) * cL
            if i == j:
                F += cS
                ss += F * F
            else:
                ss += 2 * F * F
    r = math.isqrt(ss)
    if r * r < ss:
        r += 1
    return sq + Q(r, M)


def bareiss_pd(Y, D, tau):
    """Exact test that Y + tau I is positive definite (all leading principal minors > 0, fraction-free)."""
    n = len(Y)
    A = [[Y[i][j] * tau.denominator + (D * tau.numerator if i == j else 0) for j in range(n)] for i in range(n)]
    prev = 1
    for k in range(n):
        p = A[k][k]
        if p <= 0:
            return False
        rk = A[k]
        for i in range(k + 1, n):
            ri, f = A[i], A[i][k]
            for j in range(k + 1, n):
                ri[j] = (ri[j] * p - f * rk[j]) // prev
        prev = p
    return True


# ------------------------------------------------------------------ driver

def load(path):
    raw = open(path, "rb").read()
    if path.endswith(".gz"):
        raw = gzip.decompress(raw)
    return json.loads(raw)


def check(cand, catalog, sigma=None, tau_stated=None):
    ineq = catalog[cand["inequality"]]
    if cand["type"] == "strategy":
        v = strategy_violation(cand, ineq)
        return {"type": "strategy", "inequality": cand["inequality"], "violation_exact": str(v), "violation": float(v)}
    if cand["type"] != "sos":
        raise Bad("type must be strategy or sos")
    lam, n, D, Y = sos_lambda(cand, ineq)
    out = {"type": "sos", "inequality": cand["inequality"], "n_words": n, "lambda_exact": str(lam)}
    if sigma is None:
        return out
    t = exact_shift(Y, D, sigma)
    if t is None:
        raise Bad(f"no Cholesky factor of mid(Y) + sigma I at the stated sigma {sigma!r}")
    out["tau_exact"] = str(t)
    out["tau_exact_float"] = float(t)
    b0 = rational(ineq.get("b0", 0))
    out["bound_exact_replay"] = str(lam + n * t - b0)
    if tau_stated is not None:
        out["tau_ok"] = t <= tau_stated
        if n <= BAREISS_MAX_N:
            out["bareiss_at_stated_tau"] = bareiss_pd(Y, D, tau_stated)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cert")
    ap.add_argument("--catalog", required=True)
    ap.add_argument("--sigma", help="stated Cholesky shift, as float.hex() or decimal")
    ap.add_argument("--tau-stated", help="stated tau as an exact rational p/q")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()
    cat = json.load(open(a.catalog))["inequalities"]
    sig = None if a.sigma is None else (float.fromhex(a.sigma) if "0x" in a.sigma else float(a.sigma))
    try:
        out = check(load(a.cert), cat, sig, Q(a.tau_stated) if a.tau_stated else None)
    except (Bad, KeyError, TypeError, ValueError) as e:
        print(f"REJECT: {e}")
        return 1
    print(json.dumps(out, indent=1) if a.json else out)
    return 0 if out.get("tau_ok", True) and out.get("bareiss_at_stated_tau", True) else 1


if __name__ == "__main__":
    sys.exit(main())
